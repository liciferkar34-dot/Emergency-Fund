export function getLang() {
  return localStorage.getItem("peerfund_lang") || "en";
}

export function setLang(lang) {
  localStorage.setItem("peerfund_lang", lang);
  applyTranslations();
  window.dispatchEvent(new Event("languageChanged"));
}

export function toggleLang() {
  const next = getLang() === "bn" ? "en" : "bn";
  setLang(next);
  return next;
}

export function t(key) {
  const lang = getLang();
  return (translations[lang] && translations[lang][key]) || translations.en[key] || key;
}

export function applyTranslations() {
  const lang = getLang();
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (translations[lang] && translations[lang][key]) {
      el.textContent = translations[lang][key];
    }
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (translations[lang] && translations[lang][key]) {
      el.placeholder = translations[lang][key];
    }
  });
  document.querySelectorAll(".lang-indicator").forEach((el) => {
    el.textContent = lang === "bn" ? "English" : "বাংলা";
  });
}

function initI18n() {
  applyTranslations();
  document.querySelectorAll(".lang-toggle-btn").forEach((btn) => {
    if (!btn.dataset.i18nBound) {
      btn.dataset.i18nBound = "1";
      btn.addEventListener("click", () => {
        toggleLang();
      });
    }
  });
}

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", initI18n);
} else {
  initI18n();
}
